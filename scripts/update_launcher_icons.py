#!/usr/bin/env python3
"""Give every product in Ski/manifest.xml a launcher icon of its exact size.

The launcher icon is drawn once, in Ski/resources/drawables/launcher_icon.svg. For each launcher
size used by the manifest's products this writes Ski/launcher-icons/<W>x<H>/, and it maps every
product to its folder in Ski/monkey.jungle, so the compiler renders the SVG at the right size
instead of warning that it has to rescale it.

Rerun it after changing the product list or the SVG. It reads launcher sizes from the device
files installed by the Connect IQ SDK Manager.
"""
import json
import os
import re
import shutil

SKI = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Ski")
DEVICES = os.path.expanduser("~/Library/Application Support/Garmin/ConnectIQ/Devices")
ICON = os.path.join(SKI, "resources", "drawables", "launcher_icon.svg")
OUT = os.path.join(SKI, "launcher-icons")
BEGIN = "# BEGIN launcher icon sizes (generated by scripts/update_launcher_icons.py)"
END = "# END launcher icon sizes"


def launcher_size(product):
    with open(os.path.join(DEVICES, product, "compiler.json")) as f:
        icon = json.load(f)["launcherIcon"]
    return icon["width"], icon["height"]


def write_size_folder(width, height, svg):
    folder = os.path.join(OUT, f"{width}x{height}")
    os.makedirs(folder)
    if width == height:
        bitmap = f'filename="../../resources/drawables/launcher_icon.svg" scaleX="{width}" scaleY="{height}"'
    else:
        # Scaling would stretch the round icon, so render a copy whose canvas is the target
        # size; the viewBox keeps the drawing square and centered.
        resized = re.sub(r'width="\d+" height="\d+"', f'width="{width}" height="{height}"', svg, count=1)
        with open(os.path.join(folder, "launcher_icon.svg"), "w") as f:
            f.write(resized)
        bitmap = 'filename="launcher_icon.svg"'
    with open(os.path.join(folder, "drawables.xml"), "w") as f:
        f.write(f'<drawables>\n    <bitmap id="LauncherIcon" {bitmap} />\n</drawables>\n')


def main():
    with open(os.path.join(SKI, "manifest.xml")) as f:
        products = re.findall(r'<iq:product id="([^"]+)"/>', f.read())
    sizes = {product: launcher_size(product) for product in products}
    with open(ICON) as f:
        svg = f.read()

    shutil.rmtree(OUT, ignore_errors=True)
    for width, height in sorted(set(sizes.values())):
        write_size_folder(width, height, svg)

    lines = [f"{p}.resourcePath = $({p}.resourcePath);launcher-icons/{w}x{h}" for p, (w, h) in sorted(sizes.items())]
    block = "\n".join([BEGIN, *lines, END])
    jungle_path = os.path.join(SKI, "monkey.jungle")
    with open(jungle_path) as f:
        jungle = f.read()
    if BEGIN in jungle:
        jungle = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, jungle, flags=re.S)
    else:
        jungle = jungle.rstrip("\n") + "\n\n" + block + "\n"
    with open(jungle_path, "w") as f:
        f.write(jungle)
    print(f"{len(products)} products, {len(set(sizes.values()))} launcher sizes")


if __name__ == "__main__":
    main()
